/**
 * Parse a React file generated by layoutToReactCode back into an AppLayout.
 *
 * Strategy: locate all `data-row-id` and `data-col-id` marker attributes
 * embedded by the generator, then extract the content between them.
 *
 * The algorithm walks the code linearly:
 *  1. Find each row opening tag (contains data-row-id) and record its row id.
 *  2. Find each column tag (contains data-col-id), extract col id + span width.
 *  3. The column body is everything between the opening col div and its closing.
 *
 * This is explicitly best-effort. Code that does not contain the generator
 * markers returns a single-row, single-column layout with an HtmlBlock
 * containing the original source so nothing is lost.
 */
export function reactCodeToLayout(code: string): AppLayout {
  const lines = code.split("\n");

  const rows: LayoutRow[] = [];
  let currentRow: LayoutRow | null = null;
  let currentColId: string | null = null;
  let currentColWidth = 12;
  let colBodyLines: string[] = [];
  let inColBody = false;
  // Track nesting depth inside a column so we know when the closing </div> belongs to the column
  let colNestDepth = 0;

  for (const line of lines) {
    // Row opening: <div ... data-row-id="xxx" ...>
    const rowMatch = /data-row-id="([^"]+)"/.exec(line);
    if (rowMatch !== null && line.includes("<div")) {
      // Flush any previous row
      if (currentRow !== null) {
        rows.push(currentRow);
      }
      currentRow = { id: rowMatch[1]!, columns: [] };
      currentColId = null;
      inColBody = false;
      continue;
    }

    if (currentRow === null) continue;

    // Column opening: <div className="col-span-N" data-col-id="xxx">
    const colMatch = /data-col-id="([^"]+)"/.exec(line);
    if (colMatch !== null && line.includes("<div")) {
      // Flush previous column body
      if (currentColId !== null && inColBody) {
        const component = parseComponentFromColumnBody(colBodyLines.join("\n").trim());
        const col: LayoutColumn = component !== null
          ? { id: currentColId, width: currentColWidth, component }
          : { id: currentColId, width: currentColWidth };
        currentRow.columns.push(col);
      }
      currentColId = colMatch[1]!;
      const spanMatch = /col-span-(\d+)/.exec(line);
      currentColWidth = spanMatch !== null ? parseInt(spanMatch[1]!, 10) : 12;
      colBodyLines = [];
      inColBody = true;
      colNestDepth = 0;
      continue;
    }

    if (!inColBody || currentColId === null) continue;

    // Track nesting so we know when the </div> closes the column
    const openDivs = (line.match(/<div/g) ?? []).length;
    const closeDivs = (line.match(/<\/div>/g) ?? []).length;

    // Column-closing </div> when nesting returns to -1 (we started at 0 inside the col)
    colNestDepth += openDivs - closeDivs;

    if (colNestDepth < 0) {
      // This </div> closes the column
      inColBody = false;
      if (currentRow !== null) {
        const component = parseComponentFromColumnBody(colBodyLines.join("\n").trim());
        const col: LayoutColumn = component !== null
          ? { id: currentColId, width: currentColWidth, component }
          : { id: currentColId, width: currentColWidth };
        currentRow.columns.push(col);
      }
      currentColId = null;
      colBodyLines = [];
      colNestDepth = 0;
    } else {
      colBodyLines.push(line);
    }
  }

  // Flush last row
  if (currentRow !== null && currentRow.columns.length > 0) {
    rows.push(currentRow);
  }

  // If we couldn't parse any rows, fall back to wrapping the raw code
  if (rows.length === 0) {
    return createFallbackLayout(code);
  }

  return { rows };
}

function parseComponentFromColumnBody(body: string): PlacedComponent | null {
  if (body.trim() === "") return null;

  // HtmlBlock: dangerouslySetInnerHTML
  const htmlMatch = /dangerouslySetInnerHTML=\{\{\s*__html:\s*(["'`])([\s\S]*?)\1\s*\}\}/.exec(body);
  if (htmlMatch !== null) {
    return {
      id: nanoid(),
      type: "HtmlBlock",
      props: { html: unescapeJsonString(htmlMatch[2]!) },
    };
  }

  // MarkdownBlock: <pre ... >content</pre>
  const mdMatch = /<pre[^>]*>([\s\S]*?)<\/pre>/.exec(body);
  if (mdMatch !== null) {
    return {
      id: nanoid(),
      type: "MarkdownBlock",
      props: { content: unescapeJsxText(mdMatch[1]!) },
    };
  }

  // SDK / generic JSX tag
  const tagMatch = /<([A-Z][A-Za-z0-9]*)(\s[\s\S]*?)?\s*\/>/.exec(body);
  if (tagMatch !== null) {
    const type = tagMatch[1]!;
    const attrsStr = tagMatch[2] ?? "";
    const props = parseJsxProps(attrsStr);
    const entry = getPaletteEntry(type);
    return {
      id: nanoid(),
      type,
      props: { ...(entry?.defaultProps ?? {}), ...props },
    };
  }

  return null;
}

/**
 * Naive JSX props parser. Handles string, number, boolean, and JSON literal
 * expressions — the same forms the generator emits. Does not handle nested
 * JSX, function props, or template literals.
 */
function parseJsxProps(attrsStr: string): Record<string, unknown> {
  const result: Record<string, unknown> = {};

  // String: key="value"
  const stringPattern = /(\w[\w-]*)="([^"]*)"/g;
  let m: RegExpExecArray | null;
  while ((m = stringPattern.exec(attrsStr)) !== null) {
    result[m[1]!] = m[2];
  }

  // Expression: key={value} — uses brace counting to handle nested braces
  // (e.g. key={{ nested: true }}) correctly instead of a non-greedy regex
  // which would stop at the first closing brace.
  const exprStartPattern = /(\w[\w-]*)=\{/g;
  let exprMatch: RegExpExecArray | null;
  while ((exprMatch = exprStartPattern.exec(attrsStr)) !== null) {
    const key = exprMatch[1]!;
    const contentStart = exprMatch.index + exprMatch[0].length;
    let depth = 1;
    let i = contentStart;
    while (i < attrsStr.length && depth > 0) {
      if (attrsStr[i] === "{") depth++;
      else if (attrsStr[i] === "}") depth--;
      if (depth > 0) i++;
    }
    if (depth !== 0) continue; // unbalanced — skip
    const expr = attrsStr.slice(contentStart, i).trim();
    // Boolean false
    if (expr === "false") { result[key] = false; continue; }
    // Try JSON parse for number / array / object
    try {
      result[key] = JSON.parse(expr);
    } catch {
      // Not parseable — keep as raw string
      result[key] = expr;
    }
  }

  // Bare boolean: key (no value)
  const boolPattern = /(?:^|\s)(\w[\w-]*)(?=\s|$)(?!=)/g;
  while ((m = boolPattern.exec(attrsStr)) !== null) {
    if (!(m[1]! in result)) {
      result[m[1]!] = true;
    }
  }

  return result;
}

function unescapeJsonString(raw: string): string {
  try {
    // The generator uses JSON.stringify, so the value is a JSON string literal
    return JSON.parse(`"${raw}"`);
  } catch {
    return raw;
  }
}

function unescapeJsxText(text: string): string {
  return text
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&#123;/g, "{")
    .replace(/&#125;/g, "}");
}

function createFallbackLayout(code: string): AppLayout {
  return {
    rows: [
      {
        id: nanoid(),
        columns: [
          {
            id: nanoid(),
            width: 12,
            component: {
              id: nanoid(),
              type: "HtmlBlock",
              props: {
                html: `<pre><code>${escapeJsxText(code)}</code></pre>`,
              },
            },
          },
        ],
      },
    ],
  };
}

