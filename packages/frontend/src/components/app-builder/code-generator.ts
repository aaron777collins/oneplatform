/**
 * Emit the fetch + pass-through code for a data binding.
 * This is used by the builder's "copy snippet" button — not part of the main
 * generated output, which only adds comments.
 */
export function dataBindingToHookSnippet(binding: DataBinding, componentProp: string): string {
  return [
    `// Bind "${binding.entityType}" data to ${componentProp}`,
    `const { data: ${binding.entityType}Data } = useQuery({`,
    `  queryKey: ["${binding.entityType}"],`,
    `  queryFn: ({ signal }) => client.get(\`/v1/entities/${binding.entityType}\`, undefined, { signal }),`,
    `});`,
    ``,
    `// Map fields: ${JSON.stringify(binding.fieldMap)}`,
    `const ${componentProp} = (${binding.entityType}Data?.data ?? []).map((item: Record<string, unknown>) => ({`,
    ...Object.entries(binding.fieldMap).map(([prop, field]) => `  ${prop}: item[${JSON.stringify(field)}],`),
    `}));`,
  ].join("\n");
}
